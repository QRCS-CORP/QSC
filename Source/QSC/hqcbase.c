static void gf_generate(uint16_t* exp, uint16_t* log, const int16_t m)
{
    uint16_t elt;
    uint16_t alpha;
    uint16_t gf_poly;

    elt = 1U;
    alpha = 2U;
    gf_poly = PARAM_GF_POLY;

    for (size_t i = 0U; i < (1U << m) - 1U; ++i)
    {
        exp[i] = elt;
        log[elt] = (uint16_t)i;

        elt *= alpha;

        if (elt >= 1 << m)
        {
            elt ^= gf_poly;
        }
    }

    exp[((size_t)1 << m) - 1U] = 1U;
    exp[(size_t)1 << m] = 2U;
    exp[((size_t)1 << m) + 1U] = 4U;
    log[0U] = 0U;
}

uint16_t gf_reduce(uint16_t x)
{
    uint64_t mod;
    uint16_t dist;
    uint16_t z1;
    uint16_t z2;

    /* for deg(x) = 2 * (8 - 1) = 14, reduce twice to bring degree < 8 */
    const int reduction_steps = 2;
    /* number of feedback positions */
    const size_t gf_reduction_tap_count = 3U;

    for (int32_t i = 0; i < reduction_steps; ++i)
    {
        /* extract upper bits */
        mod = x >> PARAM_M;
        /* keep lower bits */
        x &= (1U << PARAM_M) - 1U;
        /* pre - XOR with no shift */
        x ^= mod;

        z1 = 0U;

        for (size_t j = gf_reduction_tap_count; j; --j)
        {
            z2 = gf_reduction_taps[j - 1U];
            dist = z2 - z1;
            mod <<= dist;
            x ^= mod;
            z1 = z2;
        }
    }

    return x;
}

void gf_carryless_mul(uint8_t* c, uint8_t a, uint8_t b)
{
    uint16_t u[4U] = { 0U };
    uint16_t h;
    uint16_t g;
    uint16_t l;
    uint16_t maskz;
    uint16_t tmp1;
    uint16_t tmp3;
    uint32_t mask;
    uint32_t tmp2;


    h = 0U;
    l = 0U;
    u[0U] = 0U;
    u[1U] = b & ((1UL << 7) - 1UL);
    u[2U] = u[1U] << 1;
    u[3U] = u[2U] ^ u[1];

    g = 0U;
    tmp1 = a & 3;

    for (int32_t i = 0; i < 4; i++)
    {
        tmp2 = tmp1 - i;
        mask = (uint32_t)0U - (uint32_t)(1U ^ (((tmp2 | (uint32_t)(0U - tmp2)) >> 31) & 1U));
        g ^= (u[i] & mask);
    }

    l = g;
    h = 0U;

    for (uint8_t i = 2U; i < 8U; i += 2U)
    {
        g = 0U;
        tmp3 = (a >> i) & 3;

        for (int32_t j = 0; j < 4; ++j)
        {
            tmp2 = tmp3 - j;
            mask = (uint32_t)0U - (uint32_t)(1U ^ (((tmp2 | (uint32_t)(0U - tmp2)) >> 31) & 1U));
            g ^= (u[j] & mask);
        }

        l ^= g << i;
        h ^= g >> (8U - i);
    }

    maskz = (-((b >> 7) & 1));
    l ^= ((a << 7) & maskz);
    h ^= ((a >> (1)) & maskz);

    c[0U] = (uint8_t)l;
    c[1U] = (uint8_t)h;
}

uint16_t gf_mul(uint16_t a, uint16_t b)
{
    uint8_t c[2U] = { 0U };
    uint16_t tmp;

    gf_carryless_mul(c, (uint8_t)a, (uint8_t)b);
    tmp = (uint16_t)(c[0U] ^ (c[1U] << 8));

    return gf_reduce(tmp);
}

uint16_t gf_square(uint16_t a)
{
    uint32_t b;
    uint32_t s;

    b = a;
    s = b & 1;

    for (size_t i = 1U; i < PARAM_M; ++i)
    {
        b <<= 1;
        s ^= b & (1 << 2 * i);
    }

    return gf_reduce((uint16_t)s);
}

uint16_t gf_inverse(uint16_t a)
{
    uint16_t inv = a;
    uint16_t tmp1, tmp2;

    inv = gf_square(a);       /* a^2 */
    tmp1 = gf_mul(inv, a);    /* a^3 */
    inv = gf_square(inv);     /* a^4 */
    tmp2 = gf_mul(inv, tmp1); /* a^7 */
    tmp1 = gf_mul(inv, tmp2); /* a^11 */
    inv = gf_mul(tmp1, inv);  /* a^15 */
    inv = gf_square(inv);     /* a^30 */
    inv = gf_square(inv);     /* a^60 */
    inv = gf_square(inv);     /* a^120 */
    inv = gf_mul(inv, tmp2);  /* a^127 */
    inv = gf_square(inv);     /* a^254 */

    return inv;
}

