/**
 * \brief Return an all-ones mask when the least-significant bit is set.
 * \param value Integer input whose low bit is examined.
 * \return Zero when that bit is clear, or -1 when set.
 * \note No shared state; safe for concurrent callers.
 */
static inline int32_t hqc_bit0mask(size_t value)
{
    int32_t result;

    result = -(int32_t)(value & 1U);
    return result;
}

