{
    qsc_memutils_copy(c_pke->u, ct, VEC_N_SIZE_BYTES);
    qsc_memutils_copy(c_pke->v, ct + VEC_N_SIZE_BYTES, VEC_N1N2_SIZE_BYTES);
    qsc_memutils_copy(salt, ct + VEC_N_SIZE_BYTES + VEC_N1N2_SIZE_BYTES, SALT_BYTES);
}

static void hqc_pke_keygen(uint8_t* ek_pke, uint8_t* dk_pke, uint8_t* seed)
{
    qsc_keccak_state dk_xof_ctx = { 0U };
    qsc_keccak_state ek_xof_ctx = { 0U };
    uint8_t keypair_seed[2U * SEED_BYTES] = { 0U };
    uint64_t h[VEC_N_SIZE_64] = { 0U };
    uint64_t s[VEC_N_SIZE_64] = { 0U };
    uint64_t x[VEC_N_SIZE_64] = { 0U };
    uint64_t y[VEC_N_SIZE_64] = { 0U };
    uint8_t *seed_dk = keypair_seed;
    uint8_t *seed_ek = keypair_seed + SEED_BYTES;

    /* derive keypair seeds */
    hash_i(keypair_seed, seed);

    /* compute decryption key */
    xof_init(&dk_xof_ctx, seed_dk, SEED_BYTES);
    vect_sample_fixed_weight1(&dk_xof_ctx, y, PARAM_OMEGA);
    vect_sample_fixed_weight1(&dk_xof_ctx, x, PARAM_OMEGA);

    /* compute encryption key */
    xof_init(&ek_xof_ctx, seed_ek, SEED_BYTES);
    vect_set_random(&ek_xof_ctx, h);
    vect_mul(s, y, h);
    vect_add(s, x, s, VEC_N_SIZE_64);

    /* parse encryption key to string */
    qsc_memutils_copy(ek_pke, seed_ek, SEED_BYTES);
    qsc_memutils_copy(ek_pke + SEED_BYTES, s, VEC_N_SIZE_BYTES);

    /* parse decryption key to string */
    qsc_memutils_copy(dk_pke, seed_dk, SEED_BYTES);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(keypair_seed, sizeof keypair_seed);
    qsc_memutils_secure_erase(x, sizeof x);
    qsc_memutils_secure_erase(y, sizeof y);
    qsc_memutils_secure_erase(&dk_xof_ctx, sizeof dk_xof_ctx);
}

static void hqc_pke_encrypt(qsc_hqc_ciphertext_pke* c_pke, const uint8_t* ek_pke, const uint64_t* m, const uint8_t* theta)
{
    qsc_keccak_state theta_xof_ctx = { 0U };
    uint64_t h[VEC_N_SIZE_64] = { 0U };
    uint64_t s[VEC_N_SIZE_64] = { 0U };
    uint64_t r1[VEC_N_SIZE_64] = { 0U };
    uint64_t r2[VEC_N_SIZE_64] = { 0U };
    uint64_t e[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp[VEC_N_SIZE_64] = { 0U };

    /* initialize Xof using theta */
    xof_init(&theta_xof_ctx, theta, SEED_BYTES);

    /* retrieve h and s from public key */
    hqc_ek_pke_from_string(h, s, ek_pke);

    /* generate re, e and r1 */
    vect_sample_fixed_weight2(&theta_xof_ctx, r2, PARAM_OMEGA_R);
    vect_sample_fixed_weight2(&theta_xof_ctx, e, PARAM_OMEGA_E);
    vect_sample_fixed_weight2(&theta_xof_ctx, r1, PARAM_OMEGA_R);

    /* compute u = r1 + r2.h */
    vect_mul(c_pke->u, r2, h);
    vect_add(c_pke->u, r1, c_pke->u, VEC_N_SIZE_64);

    /* compute v = C.encode(m) */
    code_encode(c_pke->v, m);

    /* compute v = C.encode(m) + Truncate(s.r2 + e) */
    vect_mul(tmp, r2, s);
    vect_add(tmp, e, tmp, VEC_N_SIZE_64);
    vect_truncate(tmp);
    vect_add(c_pke->v, c_pke->v, tmp, VEC_N1N2_SIZE_64);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(r1, sizeof r1);
    qsc_memutils_secure_erase(r2, sizeof r2);
    qsc_memutils_secure_erase(e, sizeof e);
    qsc_memutils_secure_erase(tmp, sizeof tmp);
    qsc_memutils_secure_erase(&theta_xof_ctx, sizeof theta_xof_ctx);
}

static uint8_t hqc_pke_decrypt(uint64_t* m, const uint8_t* dk_pke, const qsc_hqc_ciphertext_pke* c_pke)
{
    uint64_t y[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp1[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp2[VEC_N_SIZE_64] = { 0U };

    /* parse decryption key dk_pke */
    hqc_dk_pke_from_string(y, dk_pke);

    /* compute u.y */
    vect_mul(tmp1, y, c_pke->u);
    /* truncate(u.y) */
    vect_truncate(tmp1);
    /* compute v - Truncate(u.y) */
    vect_add(tmp2, c_pke->v, tmp1, VEC_N1N2_SIZE_64);

    /* compute plaintext m */
    code_decode(m, tmp2);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(y, sizeof y);
    qsc_memutils_secure_erase(tmp1, sizeof tmp1);
    qsc_memutils_secure_erase(tmp2, sizeof tmp2);

    return 0;
}

static void qsc_hqc_ref_derive_keygen_seed_material(uint8_t seed_pke[SEED_BYTES], uint8_t sigma[PARAM_SECURITY_BYTES], const uint8_t seed_kem[SEED_BYTES])
{
    qsc_keccak_state ctx_kem = { 0U };

    xof_init(&ctx_kem, seed_kem, SEED_BYTES);
    xof_get_bytes(&ctx_kem, seed_pke, SEED_BYTES);
    xof_get_bytes(&ctx_kem, sigma, PARAM_SECURITY_BYTES);
    qsc_memutils_secure_erase(&ctx_kem, sizeof(ctx_kem));
}

static void qsc_hqc_ref_encapsulate_from_material(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, const uint8_t m[PARAM_SECURITY_BYTES], const uint8_t salt[SALT_BYTES])
{
    uint8_t ktheta[SHARED_SECRET_BYTES + SEED_BYTES] = { 0U };
    uint8_t theta[SEED_BYTES] = { 0U };
    uint8_t hashpk[SEED_BYTES] = { 0U };
    qsc_hqc_ciphertext_kem c_kem_t = { 0U };

    hash_h(hashpk, publickey);
    hash_g(ktheta, hashpk, m, salt);
    qsc_memutils_copy(theta, ktheta + SHARED_SECRET_BYTES, SEED_BYTES);
    qsc_memutils_copy(c_kem_t.salt, salt, SALT_BYTES);
    hqc_pke_encrypt(&c_kem_t.c_pke, publickey, (const uint64_t*)m, theta);
    hqc_c_kem_to_string(ciphertext, &c_kem_t);
    qsc_memutils_copy(secret, ktheta, SHARED_SECRET_BYTES);
    qsc_memutils_secure_erase(ktheta, sizeof(ktheta)); qsc_memutils_secure_erase(theta, sizeof(theta)); 
    qsc_memutils_secure_erase(hashpk, sizeof(hashpk)); qsc_memutils_secure_erase(&c_kem_t, sizeof(c_kem_t));
}

bool qsc_hqc_ref_generate_keypair(uint8_t* publickey, uint8_t* privatekey, bool (*rng_generate)(uint8_t*, size_t))
{
    uint8_t seed_kem[SEED_BYTES] = { 0U };
    uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t seed_pke[SEED_BYTES] = { 0U };
    uint8_t dk_pke[SEED_BYTES] = { 0U };
    bool res;

    res = false;

    if (publickey != NULL && privatekey != NULL && rng_generate != NULL)
    {
        res = rng_generate(seed_kem, SEED_BYTES);

        if (res == true) 
        {
            qsc_hqc_ref_derive_keygen_seed_material(seed_pke, sigma, seed_kem);
            hqc_pke_keygen(publickey, dk_pke, seed_pke);
            qsc_memutils_copy(privatekey, publickey, PUBLIC_KEY_BYTES);
            qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES, dk_pke, SEED_BYTES);
            qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES + SEED_BYTES, sigma, PARAM_SECURITY_BYTES);
            qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES + SEED_BYTES + PARAM_SECURITY_BYTES, seed_kem, SEED_BYTES);
        }
    }

    qsc_memutils_secure_erase(seed_kem, sizeof(seed_kem)); 
    qsc_memutils_secure_erase(sigma, sizeof(sigma)); 
    qsc_memutils_secure_erase(seed_pke, sizeof(seed_pke)); 
    qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke));
    
    return res;
}

void qsc_hqc_ref_generate_seeded_keypair(uint8_t* publickey, uint8_t* privatekey, uint8_t* seed)
{
    uint8_t seed_pke[SEED_BYTES] = { 0U };
    uint8_t dk_pke[SEED_BYTES] = { 0U };
    uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };

    if (publickey != NULL && privatekey != NULL && seed != NULL) 
    {
        qsc_hqc_ref_derive_keygen_seed_material(seed_pke, sigma, seed);
        hqc_pke_keygen(publickey, dk_pke, seed_pke);
        qsc_memutils_copy(privatekey, publickey, PUBLIC_KEY_BYTES);
        qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES, dk_pke, SEED_BYTES);
        qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES + SEED_BYTES, sigma, PARAM_SECURITY_BYTES);
        qsc_memutils_copy(privatekey + PUBLIC_KEY_BYTES + SEED_BYTES + PARAM_SECURITY_BYTES, seed, SEED_BYTES);
    }

    qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke)); 
    qsc_memutils_secure_erase(sigma, sizeof(sigma));
    qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke));
}

bool qsc_hqc_ref_encapsulate(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, bool (*rng_generate)(uint8_t*, size_t))
{
    uint8_t m[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t salt[SALT_BYTES] = { 0U };
    bool res;

    res = false;

    if (secret != NULL && ciphertext != NULL && publickey != NULL && rng_generate != NULL) 
    {
        res = (rng_generate(m, PARAM_SECURITY_BYTES) && rng_generate(salt, SALT_BYTES));

        if (res == true) 
        { 
            qsc_hqc_ref_encapsulate_from_material(secret, ciphertext, publickey, m, salt); 
        }
    }

    qsc_memutils_secure_erase(m, sizeof(m)); qsc_memutils_secure_erase(salt, sizeof(salt));

    return res;
}

void qsc_hqc_ref_seeded_encapsulate(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, const uint8_t seed[QSC_HQC_SEED_SIZE])
{
    uint8_t material[PARAM_SECURITY_BYTES + SALT_BYTES] = { 0U };
    qsc_keccak_state ctx = { 0U };

    if (secret != NULL && ciphertext != NULL && publickey != NULL && seed != NULL) 
    {
        xof_init(&ctx, seed, QSC_HQC_SEED_SIZE);
        xof_get_bytes(&ctx, material, (uint32_t)sizeof(material));
        qsc_hqc_ref_encapsulate_from_material(secret, ciphertext, publickey, material, material + PARAM_SECURITY_BYTES);
        qsc_memutils_secure_erase(&ctx, sizeof(ctx));
    }

    qsc_memutils_secure_erase(material, sizeof(material));
}

bool qsc_hqc_ref_decapsulate(uint8_t* secret, const uint8_t* ciphertext, const uint8_t* privatekey)
{
    uint8_t ek_pke[PUBLIC_KEY_BYTES] = { 0U };
    uint8_t dk_pke[SEED_BYTES] = { 0U };
    uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t m_prime[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t hash_ek_kem[SEED_BYTES] = { 0U };
    uint8_t ktheta_prime[SHARED_SECRET_BYTES + SEED_BYTES] = { 0U };
    uint8_t k_bar[SHARED_SECRET_BYTES] = { 0U };
    uint8_t theta_prime[SEED_BYTES] = { 0U };
    qsc_hqc_ciphertext_kem c_kem_t = { 0U };
    qsc_hqc_ciphertext_kem c_kem_prime_t = { 0U };
    uint8_t result;
    bool res;

    result = 1U;
    res = false;

    if (secret != NULL && ciphertext != NULL && privatekey != NULL)
    {
        qsc_memutils_copy(ek_pke, privatekey, PUBLIC_KEY_BYTES);
        qsc_memutils_copy(dk_pke, privatekey + PUBLIC_KEY_BYTES, SEED_BYTES);
        qsc_memutils_copy(sigma, privatekey + PUBLIC_KEY_BYTES + SEED_BYTES, PARAM_SECURITY_BYTES);
        hqc_c_kem_from_string(&c_kem_t.c_pke, c_kem_t.salt, ciphertext);
        result = hqc_pke_decrypt((uint64_t*)m_prime, dk_pke, &c_kem_t.c_pke);
        hash_h(hash_ek_kem, ek_pke);
        hash_g(ktheta_prime, hash_ek_kem, m_prime, c_kem_t.salt);
        qsc_memutils_copy(secret, ktheta_prime, SHARED_SECRET_BYTES);
        qsc_memutils_copy(theta_prime, ktheta_prime + SHARED_SECRET_BYTES, SEED_BYTES);
        hqc_pke_encrypt(&c_kem_prime_t.c_pke, ek_pke, (const uint64_t*)m_prime, theta_prime);
        qsc_memutils_copy(c_kem_prime_t.salt, c_kem_t.salt, SALT_BYTES);
        hash_j(k_bar, hash_ek_kem, sigma, &c_kem_t);
        result |= vect_compare((const uint8_t*)c_kem_t.c_pke.u, (const uint8_t*)c_kem_prime_t.c_pke.u, VEC_N_SIZE_BYTES);
        result |= vect_compare((const uint8_t*)c_kem_t.c_pke.v, (const uint8_t*)c_kem_prime_t.c_pke.v, VEC_N1N2_SIZE_BYTES);
        result |= vect_compare(c_kem_t.salt, c_kem_prime_t.salt, SALT_BYTES);
        result = (uint8_t)(result - 1U);

        for (size_t i = 0U; i < SHARED_SECRET_BYTES; ++i) 
        { 
            secret[i] = (uint8_t)((secret[i] & result) ^ (k_bar[i] & (uint8_t)~result)); 
        }

        res = true;
    }

    qsc_memutils_secure_erase(ek_pke, sizeof(ek_pke)); 
    qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke)); 
    qsc_memutils_secure_erase(sigma, sizeof(sigma)); 
    qsc_memutils_secure_erase(m_prime, sizeof(m_prime)); 
    qsc_memutils_secure_erase(hash_ek_kem, sizeof(hash_ek_kem)); 
    qsc_memutils_secure_erase(ktheta_prime, sizeof(ktheta_prime)); 
    qsc_memutils_secure_erase(k_bar, sizeof(k_bar)); 
    qsc_memutils_secure_erase(theta_prime, sizeof(theta_prime));
    qsc_memutils_secure_erase(&c_kem_t, sizeof(c_kem_t)); 
    qsc_memutils_secure_erase(&c_kem_prime_t, sizeof(c_kem_prime_t));

    return res;
}

