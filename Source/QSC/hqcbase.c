static uint16_t gf_reduce(uint16_t x)
{
    uint64_t mod;
    uint16_t dist;
    uint16_t z1;
    uint16_t z2;

    /* for deg(x) = 2 * (8 - 1) = 14, reduce twice to bring degree < 8 */
    const int32_t reduction_steps = 2;
    /* number of feedback positions */
    const size_t gf_reduction_tap_count = 3U;

    for (int32_t i = 0; i < reduction_steps; ++i)
    {
        /* extract upper bits */
        mod = x >> PARAM_M;
        /* keep lower bits */
        x &= (1U << PARAM_M) - 1U;
        /* pre - XOR with no shift */
        x ^= mod;

        z1 = 0U;

        for (size_t j = gf_reduction_tap_count; j; --j)
        {
            z2 = gf_reduction_taps[j - 1U];
            dist = z2 - z1;
            mod <<= dist;
            x ^= mod;
            z1 = z2;
        }
    }

    return x;
}

static void gf_carryless_mul(uint8_t* c, uint8_t a, uint8_t b)
{
    uint16_t u[4U] = { 0U };
    uint16_t h;
    uint16_t g;
    uint16_t l;
    uint16_t maskz;
    uint16_t tmp1;
    uint16_t tmp3;
    uint32_t mask;
    uint32_t tmp2;


    h = 0U;
    l = 0U;
    u[0U] = 0U;
    u[1U] = b & ((1UL << 7) - 1UL);
    u[2U] = u[1U] << 1;
    u[3U] = u[2U] ^ u[1];

    g = 0U;
    tmp1 = a & 3;

    for (int32_t i = 0; i < 4; i++)
    {
        tmp2 = tmp1 - i;
        mask = (uint32_t)0U - (uint32_t)(1U ^ (((tmp2 | (uint32_t)(0U - tmp2)) >> 31) & 1U));
        g ^= (u[i] & mask);
    }

    l = g;
    h = 0U;

    for (uint8_t i = 2U; i < 8U; i += 2U)
    {
        g = 0U;
        tmp3 = (a >> i) & 3;

        for (int32_t j = 0; j < 4; ++j)
        {
            tmp2 = tmp3 - j;
            mask = (uint32_t)0U - (uint32_t)(1U ^ (((tmp2 | (uint32_t)(0U - tmp2)) >> 31) & 1U));
            g ^= (u[j] & mask);
        }

        l ^= g << i;
        h ^= g >> (8U - i);
    }

    maskz = (-((b >> 7) & 1));
    l ^= ((a << 7) & maskz);
    h ^= ((a >> (1)) & maskz);

    c[0U] = (uint8_t)l;
    c[1U] = (uint8_t)h;
}

static uint16_t gf_mul(uint16_t a, uint16_t b)
{
    uint8_t c[2U] = { 0U };
    uint16_t tmp;

    gf_carryless_mul(c, (uint8_t)a, (uint8_t)b);
    tmp = (uint16_t)(c[0U] ^ (c[1U] << 8));

    return gf_reduce(tmp);
}

static uint16_t gf_square(uint16_t a)
{
    uint32_t b;
    uint32_t s;

    b = a;
    s = b & 1;

    for (size_t i = 1U; i < PARAM_M; ++i)
    {
        b <<= 1;
        s ^= b & (1 << 2 * i);
    }

    return gf_reduce((uint16_t)s);
}

static uint16_t gf_inverse(uint16_t a)
{
    uint16_t inv = a;
    uint16_t tmp1, tmp2;

    inv = gf_square(a);       /* a^2 */
    tmp1 = gf_mul(inv, a);    /* a^3 */
    inv = gf_square(inv);     /* a^4 */
    tmp2 = gf_mul(inv, tmp1); /* a^7 */
    tmp1 = gf_mul(inv, tmp2); /* a^11 */
    inv = gf_mul(tmp1, inv);  /* a^15 */
    inv = gf_square(inv);     /* a^30 */
    inv = gf_square(inv);     /* a^60 */
    inv = gf_square(inv);     /* a^120 */
    inv = gf_mul(inv, tmp2);  /* a^127 */
    inv = gf_square(inv);     /* a^254 */

    return inv;
}

static void compute_fft_betas(uint16_t* betas) 
{
    for (size_t i = 0; i < PARAM_M - 1; ++i) 
    {
        betas[i] = 1 << (PARAM_M - 1 - i);
    }
}

static void compute_subset_sums(uint16_t* subset_sums, const uint16_t* set, uint16_t set_size) 
{
    subset_sums[0U] = 0U;

    for (uint16_t i = 0U; i < set_size; ++i) 
    {
        for (uint16_t j = 0U; j < (1 << i); ++j)
        {
            subset_sums[(1U << i) + j] = set[i] ^ subset_sums[j];
        }
    }
}

static void radix_big(uint16_t* f0, uint16_t* f1, const uint16_t* f, uint32_t m_f);

static void radix(uint16_t* f0, uint16_t* f1, const uint16_t* f, uint32_t m_f)
{
    switch (m_f) 
    {
        case 4:
            f0[4U] = f[8U] ^ f[12U];
            f0[6U] = f[12U] ^ f[14U];
            f0[7U] = f[14U] ^ f[15U];
            f1[5U] = f[11U] ^ f[13U];
            f1[6U] = f[13U] ^ f[14U];
            f1[7U] = f[15U];
            f0[5U] = f[10U] ^ f[12U] ^ f1[5U];
            f1[4U] = f[9U] ^ f[13U] ^ f0[5U];

            f0[0U] = f[0U];
            f1[3U] = f[7U] ^ f[11U] ^ f[15];
            f0[3U] = f[6U] ^ f[10U] ^ f[14] ^ f1[3U];
            f0[2U] = f[4U] ^ f0[4U] ^ f0[3] ^ f1[3U];
            f1[1U] = f[3U] ^ f[5U] ^ f[9] ^ f[13] ^ f1[3U];
            f1[2U] = f[3U] ^ f1[1U] ^ f0[3U];
            f0[1U] = f[2U] ^ f0[2U] ^ f1[1U];
            f1[0U] = f[1U] ^ f0[1U];
            break;

        case 3:
            f0[0U] = f[0U];
            f0[2U] = f[4U] ^ f[6U];
            f0[3U] = f[6U] ^ f[7U];
            f1[1U] = f[3U] ^ f[5U] ^ f[7U];
            f1[2U] = f[5U] ^ f[6U];
            f1[3U] = f[7U];
            f0[1U] = f[2U] ^ f0[2U] ^ f1[1U];
            f1[0U] = f[1U] ^ f0[1U];
            break;

        case 2:
            f0[0U] = f[0U];
            f0[1U] = f[2U] ^ f[3U];
            f1[0U] = f[1U] ^ f0[1U];
            f1[1U] = f[3U];
            break;

        case 1:
            f0[0U] = f[0U];
            f1[0U] = f[1U];
            break;

        default:
            radix_big(f0, f1, f, m_f);
            break;
    }
}

static void radix_big(uint16_t* f0, uint16_t* f1, const uint16_t* f, uint32_t m_f) 
{
    uint16_t Q[2U * (1U << (PARAM_FFT - 2U)) + 1U] = { 0U };
    uint16_t R[2U * (1U << (PARAM_FFT - 2U)) + 1U] = { 0U };
    uint16_t Q0[1U << (PARAM_FFT - 2U)] = { 0U};
    uint16_t Q1[1U << (PARAM_FFT - 2U)] = { 0U };
    uint16_t R0[1U << (PARAM_FFT - 2U)] = { 0U };
    uint16_t R1[1U << (PARAM_FFT - 2U)] = { 0U };

    size_t i;
    size_t n;

    n = 1U;
    n <<= (m_f - 2U);
    qsc_memutils_copy(Q, f + 3U * n, 2U * n);
    qsc_memutils_copy(Q + n, f + 3U * n, 2U * n);
    qsc_memutils_copy(R, f, 4U * n);

    for (i = 0U; i < n; ++i)
    {
        Q[i] ^= f[2U * n + i];
        R[n + i] ^= Q[i];
    }

    radix(Q0, Q1, Q, m_f - 1U);
    radix(R0, R1, R, m_f - 1U);

    qsc_memutils_copy(f0, R0, 2U * n);
    qsc_memutils_copy(f0 + n, Q0, 2U * n);
    qsc_memutils_copy(f1, R1, 2U * n);
    qsc_memutils_copy(f1 + n, Q1, 2U * n);
}

static void fft_rec(uint16_t* w, uint16_t* f, size_t f_coeffs, uint8_t m, uint32_t m_f, const uint16_t* betas)
{
    uint16_t f0[1U << (PARAM_FFT - 2U)] = { 0U };
    uint16_t f1[1U << (PARAM_FFT - 2U)] = { 0U };
    uint16_t gammas[PARAM_M - 2U] = { 0U };
    uint16_t deltas[PARAM_M - 2U] = { 0U };
    uint16_t gammas_sums[1U << (PARAM_M - 2U)] = { 0U };
    uint16_t u[1U << (PARAM_M - 2U)] = { 0U };
    uint16_t v[1U << (PARAM_M - 2U)] = { 0U };
    uint16_t tmp[PARAM_M - (PARAM_FFT - 1U)] = { 0U };
    uint16_t beta_m_pow;
    size_t i;
    size_t j;
    size_t k;
    size_t x;

    // Step 1
    if (m_f == 1U) 
    {
        for (i = 0U; i < m; ++i) 
        {
            tmp[i] = gf_mul(betas[i], f[1U]);
        }

        w[0U] = f[0U];
        x = 1U;

        for (j = 0; j < m; ++j) 
        {
            for (k = 0U; k < x; ++k)
            {
                w[x + k] = w[k] ^ tmp[j];
            }

            x <<= 1;
        }

        return;
    }

    /* step 2: compute g */
    if (betas[m - 1U] != 1U) 
    {
        beta_m_pow = 1U;
        x = 1U;
        x <<= m_f;

        for (i = 1U; i < x; ++i) 
        {
            beta_m_pow = gf_mul(beta_m_pow, betas[m - 1U]);
            f[i] = gf_mul(beta_m_pow, f[i]);
        }
    }

    /* step 3 */
    radix(f0, f1, f, m_f);

    /* step 4: compute gammas and deltas */
    for (i = 0U; i + 1U < m; ++i) 
    {
        gammas[i] = gf_mul(betas[i], gf_inverse(betas[m - 1]));
        deltas[i] = gf_square(gammas[i]) ^ gammas[i];
    }

    /* compute gammas sums */
    compute_subset_sums(gammas_sums, gammas, m - 1U);

    /* step 5 */
    fft_rec(u, f0, (f_coeffs + 1U) / 2U, m - 1U, m_f - 1U, deltas);

    k = 1U;
    k <<= ((m - 1U) & 0x0F);

    if (f_coeffs <= 3U) 
    {    /* 3 - coefficient polynomial f case: f1 is constant */
        w[0U] = u[0U];
        w[k] = u[0U] ^ f1[0U];

        for (i = 1U; i < k; ++i) 
        {
            w[i] = u[i] ^ gf_mul(gammas_sums[i], f1[0U]);
            w[k + i] = w[i] ^ f1[0U];
        }
    } 
    else
    {
        fft_rec(v, f1, f_coeffs / 2U, m - 1U, m_f - 1U, deltas);

        /* step 6 */
        qsc_memutils_copy(w + k, v, 2U * k);
        w[0U] = u[0U];
        w[k] ^= u[0U];

        for (i = 1U; i < k; ++i) 
        {
            w[i] = u[i] ^ gf_mul(gammas_sums[i], v[i]);
            w[k + i] ^= w[i];
        }
    }
}

static void fft(uint16_t* w, const uint16_t* f, size_t f_coeffs)
{
    uint16_t betas[PARAM_M - 1U] = { 0U };
    uint16_t betas_sums[1U << (PARAM_M - 1U)] = { 0U };
    uint16_t f0[1U << (PARAM_FFT - 1U)] = { 0U };
    uint16_t f1[1U << (PARAM_FFT - 1U)] = { 0U };
    uint16_t deltas[PARAM_M - 1U] = { 0U };
    uint16_t u[1U << (PARAM_M - 1U)] = { 0U };
    uint16_t v[1U << (PARAM_M - 1U)] = { 0U };
    size_t i;
    size_t k;

    /* follows Gao and Mateer algorithm */
    compute_fft_betas(betas);

    /* step 1: PARAM_FFT > 1, nothing to do */

    /* compute gammas sums */
    compute_subset_sums(betas_sums, betas, PARAM_M - 1U);

    /* step 2: beta_m = 1, nothing to do */

    /* step 3*/
    radix(f0, f1, f, PARAM_FFT);

    /* step 4: Compute deltas */
    for (i = 0U; i < PARAM_M - 1U; ++i)
    {
        deltas[i] = gf_square(betas[i]) ^ betas[i];
    }

    /* step 5 */
    fft_rec(u, f0, (f_coeffs + 1U) / 2U, PARAM_M - 1U, PARAM_FFT - 1U, deltas);
    fft_rec(v, f1, f_coeffs / 2U, PARAM_M - 1U, PARAM_FFT - 1U, deltas);

    k = 1U << (PARAM_M - 1U);
    /* step 6, 7 and error polynomial computation */
    qsc_memutils_copy(w + k, v, 2 * k);

    /* check if 0 is root */
    w[0U] = u[0U];

    /* check if 1 is root */
    w[k] ^= u[0U];

    /* find other roots */
    for (i = 1U; i < k; ++i)
    {
        w[i] = u[i] ^ gf_mul(betas_sums[i], v[i]);
        w[k + i] ^= w[i];
    }
}

static void fft_retrieve_error_poly(uint8_t* error, const uint16_t* w)
{
    uint16_t gammas[PARAM_M - 1U] = { 0U };
    uint16_t gammas_sums[1U << (PARAM_M - 1U)] = { 0U };
    uint16_t k;
    size_t i; 
    size_t index;

    compute_fft_betas(gammas);
    compute_subset_sums(gammas_sums, gammas, PARAM_M - 1U);

    k = 1U << (PARAM_M - 1U);
    error[0U] ^= 1U ^ ((uint16_t)-w[0U] >> 15);
    error[0U] ^= 1U ^ ((uint16_t)-w[k] >> 15);

    for (i = 1U; i < k; ++i) 
    {
        index = PARAM_GF_MUL_ORDER - gf_log[gammas_sums[i]];
        error[index] ^= 1U ^ ((uint16_t)-w[i] >> 15);

        index = PARAM_GF_MUL_ORDER - gf_log[gammas_sums[i] ^ 1U];
        error[index] ^= 1U ^ ((uint16_t)-w[k + i] >> 15);
    }
}

static void schoolbook_mul(uint64_t* r, const uint64_t* a, const uint64_t* b, size_t n)
{
    uint64_t ai;
    uint64_t mask;
    size_t base;
    int32_t sh;
    int32_t inv;

    qsc_memutils_clear(r, 2U * n * sizeof(uint64_t));

    for (size_t i = 0U; i < n; i++) 
    {
        ai = a[i];

        for (int32_t bit = 0; bit < 64; ++bit)
        {
            mask = 0ULL - ((ai >> bit) & 1ULL);
            base = i;
            sh = bit;
            inv = 64 - sh;

            if (sh == 0) 
            {
                for (size_t j = 0U; j < n; ++j)
                {
                    r[base + j] ^= b[j] & mask;
                }
            } 
            else 
            {
                for (size_t j = 0U; j < n; j++)
                {
                    r[base + j] ^= (b[j] << sh) & mask;
                    r[base + j + 1U] ^= (b[j] >> inv) & mask;
                }
            }
        }
    }
}

static void karatsuba_mul(uint64_t* r, const uint64_t* a, const uint64_t* b, size_t n, uint64_t* tmp_buffer)
{
    uint64_t* child_buffer;
    uint64_t* ta;
    uint64_t* tb;
    uint64_t* z0;
    uint64_t* z2;
    uint64_t* zmid;
    uint64_t loa;
    uint64_t lob;
    size_t m;
    size_t n0;
    size_t n1;
    uint64_t mid;
    uint64_t z0i;
    uint64_t z2i;

    if (n <= KARATSUBA_THRESHOLD)
    {
        schoolbook_mul(r, a, b, n);
    }
    else
    {
        m = n >> 1;
        n0 = m;
        n1 = n - m;

        /* take successive chunks of tmp_buffer for each intermediate result */
        z0 = tmp_buffer;   /* low-half product, size 2*n words */
        z2 = z0 + 2U * n;   /* high-half product, size 2*n words */
        zmid = z2 + 2U * n; /* middle product, size 2*n words */

        /* ta and tb hold the sums of low and high halves: */
        ta = zmid + 2U * n;
        tb = ta + n;

        /* buffer for child recursions */
        child_buffer = tmp_buffer + 8U * n;

        /* 1) low * low */
        karatsuba_mul(z0, a, b, n0, child_buffer);

        /* 2) high * high */
        karatsuba_mul(z2, a + m, b + m, n1, child_buffer);

        /* 3) (a0+a1)*(b0+b1) */
        for (size_t i = 0U; i < n1; i++)
        {
            loa = (i < n0 ? a[i] : 0U);
            lob = (i < n0 ? b[i] : 0U);
            ta[i] = loa ^ a[m + i];
            tb[i] = lob ^ b[m + i];
        }

        karatsuba_mul(zmid, ta, tb, n1, child_buffer);

        /* 4) assemble into r */
        qsc_memutils_clear(r, 2U * n * sizeof(uint64_t));

        for (size_t i = 0U; i < 2U * n0; ++i)
        {
            r[i] ^= z0[i];
        }

        for (size_t i = 0U; i < 2U * n1; ++i)
        {
            r[2U * m + i] ^= z2[i];
        }

        for (size_t i = 0U; i < 2U * n1; ++i)
        {
            z0i = (i < 2U * n0 ? z0[i] : 0U);
            z2i = (i < 2U * n1 ? z2[i] : 0U);
            mid = zmid[i] ^ z0i ^ z2i;
            r[m + i] ^= mid;
        }
    }
}

static void reduce(uint64_t* o, const uint64_t* a)
{
    for (size_t i = 0; i < VEC_N_SIZE_64; i++)
    {
        uint64_t r = a[i + VEC_N_SIZE_64 - 1U] >> (PARAM_N & 0x3F);
        uint64_t carry = a[i + VEC_N_SIZE_64] << (64 - (PARAM_N & 0x3F));
        o[i] = a[i] ^ r ^ carry;
    }

    o[VEC_N_SIZE_64 - 1U] &= ((UINT64_C(1) << (PARAM_N % 64U)) - UINT64_C(1));
}

static void vect_mul(uint64_t* o, const uint64_t* a1, const uint64_t* a2)
{
    uint64_t unreduced[2U * VEC_N_SIZE_64] = { 0U };
    uint64_t tmp_buffer[TMP_BUFFER_WORDS] = { 0U };

    /* multiply via Karatsuba into unreduced */
    karatsuba_mul(unreduced, a1, a2, VEC_N_SIZE_64, tmp_buffer);

    /* reduce modulo X^n - 1 */
    reduce(o, unreduced);
}

static void encode(rm_codeword_t *word, int32_t message)
{
    /* Encode a single byte into a single codeword using RM(1,7)
     * Encoding matrix of this code:
     * bit pattern (note that bits are numbered big endian)
     * 0   AAAAAAAA AAAAAAAA AAAAAAAA AAAAAAAA
     * 1   CCCCCCCC CCCCCCCC CCCCCCCC CCCCCCCC
     * 2   F0F0F0F0 F0F0F0F0 F0F0F0F0 F0F0F0F0
     * 3   FF00FF00 FF00FF00 FF00FF00 FF00FF00
     * 4   FFFF0000 FFFF0000 FFFF0000 FFFF0000
     * 5   FFFFFFFF 00000000 FFFFFFFF 00000000
     * 6   FFFFFFFF FFFFFFFF 00000000 00000000
     * 7   FFFFFFFF FFFFFFFF FFFFFFFF FFFFFFFF */

    int32_t first_word;

    first_word = hqc_bit0mask(message >> 7);

    first_word ^= hqc_bit0mask(message >> 0) & 0xAAAAAAAA;
    first_word ^= hqc_bit0mask(message >> 1) & 0xCCCCCCCC;
    first_word ^= hqc_bit0mask(message >> 2) & 0xF0F0F0F0;
    first_word ^= hqc_bit0mask(message >> 3) & 0xFF00FF00;
    first_word ^= hqc_bit0mask(message >> 4) & 0xFFFF0000;

    word->u32[0U] = first_word;
    first_word ^= hqc_bit0mask(message >> 5);
    word->u32[1U] = first_word;
    first_word ^= hqc_bit0mask(message >> 6);
    word->u32[3U] = first_word;
    first_word ^= hqc_bit0mask(message >> 5);
    word->u32[2U] = first_word;
}

static void hadamard(rm_expanded_cdw* src, rm_expanded_cdw* dst)
{
    rm_expanded_cdw* p1 = src;
    rm_expanded_cdw* p2 = dst;
    rm_expanded_cdw* p3;

    for (int32_t pass = 0; pass < 7; ++pass) 
    {
        for (int32_t i = 0; i < 64; ++i)
        {
            (*p2)[i] = (*p1)[2 * i] + (*p1)[2 * i + 1U];
            (*p2)[i + 64] = (*p1)[2 * i] - (*p1)[2 * i + 1U];
        }

        /* swap p1, p2 for next round */
        p3 = p1;
        p1 = p2;
        p2 = p3;
    }
}

static void expand_and_sum(rm_expanded_cdw* dest, rm_codeword_t src[])
{
    /* Accesses memory in order
     * Note: this does not write the codewords as -1 or +1 as the green machine does
     * instead, just 0 and 1 is used.
     * The resulting hadamard transform has:
     * all values are halved the first entry is 64 too high */

    /* start with the first copy */
    for (int32_t part = 0; part < 4; ++part)
    {
        for (int32_t bit = 0; bit < 32; ++bit)
        {
            (*dest)[part * 32 + bit] = src[0U].u32[part] >> bit & 1;
        }
    }

    /* sum the rest of the copies */
    for (int32_t copy = 1; (uint32_t)copy < MULTIPLICITY; ++copy) 
    {
        for (int32_t part = 0; part < 4; ++part) 
        {
            for (int32_t bit = 0; bit < 32; ++bit)
            {
                (*dest)[part * 32 + bit] += src[copy].u32[part] >> bit & 1;
            }
        }
    }
}

static int32_t find_peaks(rm_expanded_cdw* transform)
{
    /* This is the final step of the green machine: find the location of the highest value,
     * and add 128 if the peak is positive
     * if there are two identical peaks, the peak with smallest value
     * in the lowest 7 bits it taken */

    int32_t peak_abs_value;
    int32_t peak_value;
    int32_t peak_pos;

    peak_abs_value = 0;
    peak_value = 0;
    peak_pos = 0;

    for (int32_t i = 0; i < 128; i++)
    {
        /* get absolute value */
        int32_t t = (*transform)[i];
        int32_t pos_mask = -(t > 0);
        int32_t absolute = (pos_mask & t) | (~pos_mask & -t);
        peak_value = absolute > peak_abs_value ? t : peak_value;
        peak_pos = absolute > peak_abs_value ? i : peak_pos;
        peak_abs_value = absolute > peak_abs_value ? absolute : peak_abs_value;
    }

    /* set bit 7 */
    peak_pos |= 128 * (peak_value > 0);

    return peak_pos;
}

static void reed_muller_encode(uint64_t* cdw, const uint64_t* msg)
{
    /* The message consists of N1 bytes each byte is encoded into PARAM_N2 bits,
     * or MULTIPLICITY repeats of 128 bits */

    uint8_t* message_array;
    rm_codeword_t* code_array;
    int32_t pos;

    message_array = (uint8_t*)msg;
    code_array = (rm_codeword_t*)cdw;

    for (size_t i = 0U; i < VEC_N1_SIZE_BYTES; ++i)
    {
        /* fill entries i* MULTIPLICITY to(i + 1)* MULTIPLICITY */
        pos = (int32_t)i * MULTIPLICITY;
        /* encode first word */
        encode(&code_array[pos], message_array[i]);

        /* copy to other identical codewords */
        for (size_t copy = 1; copy < MULTIPLICITY; ++copy) 
        {
            qsc_memutils_copy(&code_array[pos + copy], &code_array[pos], sizeof(rm_codeword_t));
        }
    }
}

static void reed_muller_decode(uint64_t* msg, const uint64_t* cdw)
{
    /* Decoding uses fast hadamard transform, for a more complete picture on Reed-Muller decoding,
     * see MacWilliams, Florence Jessie, and Neil James Alexander Sloane.
     * The theory of error-correcting codes codes @cite macwilliams1977theory */

    uint8_t* message_array;
    rm_codeword_t* code_array;
    rm_expanded_cdw expanded;
    rm_expanded_cdw transform;

    message_array = (uint8_t*)msg;
    code_array = (rm_codeword_t*)cdw;

    for (size_t i = 0U; i < VEC_N1_SIZE_BYTES; ++i)
    {
        /* collect the codewords */
        expand_and_sum(&expanded, &code_array[i * MULTIPLICITY]);
        /* apply hadamard transform */
        hadamard(&expanded, &transform);
        /* fix the first entry to get the half Hadamard transform */
        transform[0U] -= 64 * MULTIPLICITY;
        /* finish the decoding */
        message_array[i] = (uint8_t)find_peaks(&transform);
    }
}

static void reed_solomon_encode(uint64_t* cdw, const uint64_t* msg)
{
    /* Following @cite lin1983error (Chapter 4 - Cyclic Codes),
     * We perform a systematic encoding using a linear (PARAM_N1 - PARAM_K)-stage shift register
     * with feedback connections based on the generator polynomial PARAM_RS_POLY of the Reed-Solomon code. */

    uint16_t tmp[PARAM_G] = { 0U };
    uint16_t PARAM_RS_POLY[] = { RS_POLY_COEFS };
    uint8_t msg_bytes[PARAM_K] = { 0U };
    uint8_t cdw_bytes[PARAM_N1] = { 0U };
    size_t i;
    size_t j;
    size_t k;
    uint8_t gate_value;

    gate_value = 0U;

    qsc_memutils_copy(msg_bytes, msg, PARAM_K);

    for (i = 0U; i < PARAM_K; ++i)
    {
        gate_value = msg_bytes[PARAM_K - 1U - i] ^ cdw_bytes[PARAM_N1 - PARAM_K - 1U];

        for (j = 0U; j < PARAM_G; ++j) 
        {
            tmp[j] = gf_mul(gate_value, PARAM_RS_POLY[j]);
        }

        for (k = PARAM_N1 - PARAM_K - 1U; k; --k) 
        {
            cdw_bytes[k] = cdw_bytes[k - 1U] ^ (uint8_t)tmp[k];
        }

        cdw_bytes[0U] = (uint8_t)tmp[0U];
    }

    qsc_memutils_copy(cdw_bytes + PARAM_N1 - PARAM_K, msg_bytes, PARAM_K);
    qsc_memutils_copy(cdw, cdw_bytes, PARAM_N1);
}

static void compute_syndromes(uint16_t* syndromes, uint8_t* cdw)
{
    for (size_t i = 0U; i < 2U * PARAM_DELTA; ++i)
    {
        for (size_t j = 1; j < PARAM_N1; ++j) 
        {
            syndromes[i] ^= gf_mul(cdw[j], alpha_ij_pow[i][j - 1U]);
        }

        syndromes[i] ^= cdw[0U];
    }
}

static uint16_t compute_elp(uint16_t* sigma, const uint16_t* syndromes)
{
    /* This is a constant time implementation of Berlekamp's algorithm (see @cite lin1983error (Chapter 6 - BCH
     * Codes). <br> We use the letter p for rho which is initialized at -1. <br> The array X_sigma_p represents the
     * polynomial X^(mu-rho)*sigma_p(X). Instead of maintaining a list of sigmas, we update in place both sigma and
     * X_sigma_p. sigma_copy serves as a temporary save of sigma in case X_sigma_p needs to be updated. <br> We can
     * properly correct only if the degree of sigma does not exceed PARAM_DELTA. This means only the first PARAM_DELTA + 1
     * coefficients of sigma are of value and we only need to save its first PARAM_DELTA - 1 coefficients. */

    uint16_t sigma_copy[PARAM_DELTA + 1U] = { 0U };
    uint16_t X_sigma_p[PARAM_DELTA + 1] = { 0U, 1U };
    uint16_t deg_sigma = 0U;
    uint16_t deg_sigma_p = 0U;
    uint16_t deg_sigma_copy = 0U;
    uint16_t pp = (uint16_t)-1;
    uint16_t d_p = 1U;
    uint16_t d = syndromes[0U];
    uint16_t mask1;
    uint16_t mask2;
    uint16_t mask12;
    uint16_t deg_X;
    uint16_t deg_X_sigma_p;
    uint16_t dd;
    uint16_t mu;
    uint16_t i;

    sigma[0U] = 1U;

    for (mu = 0; (mu < (2 * PARAM_DELTA)); ++mu) 
    {
        /* save sigma in case we need it to update X_sigma_p */
        qsc_memutils_copy(sigma_copy, sigma, 2U * (PARAM_DELTA));
        deg_sigma_copy = deg_sigma;

        dd = gf_mul(d, gf_inverse(d_p));

        for (i = 1U; (i <= mu + 1U) && (i <= PARAM_DELTA); ++i)
        {
            sigma[i] ^= gf_mul(dd, X_sigma_p[i]);
        }

        deg_X = mu - pp;
        deg_X_sigma_p = deg_X + deg_sigma_p;

        /* mask1 = 0xffff if (d != 0) and 0 otherwise */
        mask1 = -((uint16_t)-d >> 15);

        /* mask2 = 0xffff if (deg_X_sigma_p > deg_sigma) and 0 otherwise */
        mask2 = -((uint16_t)(deg_sigma - deg_X_sigma_p) >> 15);

        /* mask12 = 0xffff if the deg_sigma increased and 0 otherwise */
        volatile uint16_t mask12__ = mask1 & mask2;
        mask12 = mask12__;
        deg_sigma ^= mask12 & (deg_X_sigma_p ^ deg_sigma);

        if (mu == (2U * PARAM_DELTA - 1U))
        {
            break;
        }

        pp ^= mask12 & (mu ^ pp);
        d_p ^= mask12 & (d ^ d_p);

        for (i = PARAM_DELTA; i; --i) 
        {
            X_sigma_p[i] = (mask12 & sigma_copy[i - 1U]) ^ (~mask12 & X_sigma_p[i - 1U]);
        }

        deg_sigma_p ^= mask12 & (deg_sigma_copy ^ deg_sigma_p);
        d = syndromes[mu + 1];

        for (i = 1U; (i <= mu + 1U) && (i <= PARAM_DELTA); ++i) 
        {
            d ^= gf_mul(sigma[i], syndromes[mu + 1U - i]);
        }
    }

    return deg_sigma;
}

static void compute_roots(uint8_t* error, uint16_t* sigma) 
{
    uint16_t w[1U << PARAM_M] = { 0U };

    fft(w, sigma, PARAM_DELTA + 1U);
    fft_retrieve_error_poly(error, w);
}

static void compute_z_poly(uint16_t* z, const uint16_t* sigma, const uint16_t degree, const uint16_t* syndromes)
{
    size_t i;
    size_t j;
    uint16_t mask;

    z[0U] = 1U;

    for (i = 1U; i < PARAM_DELTA + 1U; ++i) 
    {
        mask = -((uint16_t)(i - degree - 1U) >> 15);
        z[i] = mask & sigma[i];
    }

    z[1U] ^= syndromes[0];

    for (i = 2U; i <= PARAM_DELTA; ++i)
    {
        mask = -((uint16_t)(i - degree - 1U) >> 15);
        z[i] ^= mask & syndromes[i - 1U];

        for (j = 1U; j < i; ++j)
        {
            z[i] ^= mask & gf_mul(sigma[j], syndromes[i - j - 1U]);
        }
    }
}

static void compute_error_values(uint16_t* error_values, const uint16_t* z, const uint8_t* error) 
{
    /* See @cite lin1983error (Chapter 6 - BCH Codes) for more details. */

    uint16_t beta_j[PARAM_DELTA] = { 0U };
    uint16_t e_j[PARAM_DELTA] = { 0U };
    uint16_t delta_counter;
    uint16_t delta_real_value;
    uint16_t found;
    uint16_t mask1;
    uint16_t mask2;
    uint16_t tmp1;
    uint16_t tmp2;
    uint16_t inverse;
    uint16_t inverse_power_j;

    /* compute the beta_{j_i} page 31 of the documentation */
    delta_counter = 0U;

    for (size_t i = 0U; i < PARAM_N1; ++i)
    {
        found = 0U;
        mask1 = (uint16_t)(-((int32_t)error[i]) >> 31);

        for (size_t j = 0U; j < PARAM_DELTA; ++j) 
        {
            mask2 = ~((uint16_t)(-((int32_t)j ^ delta_counter) >> 31));
            beta_j[j] += mask1 & mask2 & gf_exp[i];
            found += mask1 & mask2 & 1;
        }

        delta_counter += found;
    }

    delta_real_value = delta_counter;

    /* compute the e_{j_i} page 31 of the documentation */
    for (size_t i = 0U; i < PARAM_DELTA; ++i) 
    {
        tmp1 = 1U;
        tmp2 = 1U;
        inverse = gf_inverse(beta_j[i]);
        inverse_power_j = 1U;

        for (size_t j = 1U; j <= PARAM_DELTA; ++j) 
        {
            inverse_power_j = gf_mul(inverse_power_j, inverse);
            tmp1 ^= gf_mul(inverse_power_j, z[j]);
        }

        for (size_t k = 1U; k < PARAM_DELTA; ++k)
        {
            tmp2 = gf_mul(tmp2, (1 ^ gf_mul(inverse, beta_j[(i + k) % PARAM_DELTA])));
        }

        mask1 = (uint16_t)(((int16_t)i - delta_real_value) >> 15);
        e_j[i] = mask1 & gf_mul(tmp1, gf_inverse(tmp2));
    }

    /* place the delta e_{j_i} values at the right coordinates of the output vector */
    delta_counter = 0U;

    for (size_t i = 0U; i < PARAM_N1; ++i) 
    {
        found = 0U;
        mask1 = (uint16_t)(-((int32_t)error[i]) >> 31);

        for (size_t j = 0; j < PARAM_DELTA; j++) 
        {
            mask2 = ~((uint16_t)(-((int32_t)j ^ delta_counter) >> 31));
            error_values[i] += mask1 & mask2 & e_j[j];
            found += mask1 & mask2 & 1;
        }
        delta_counter += found;
    }
}

static void correct_errors(uint8_t* cdw, const uint16_t* error_values) 
{
    for (size_t i = 0U; i < PARAM_N1; ++i) 
    {
        cdw[i] ^= error_values[i];
    }
}

static void reed_solomon_decode(uint64_t* msg, uint64_t* cdw) 
{
    uint8_t cdw_bytes[PARAM_N1] = { 0U };
    uint16_t syndromes[2U * PARAM_DELTA] = { 0U };
    uint16_t sigma[1U << PARAM_FFT] = { 0U };
    uint8_t error[1U << PARAM_M] = { 0U };
    uint16_t z[PARAM_N1] = { 0U };
    uint16_t error_values[PARAM_N1] = { 0U };
    uint16_t deg;

    /* copy the vector in an array of bytes */
    qsc_memutils_copy(cdw_bytes, cdw, PARAM_N1);

    /* calculate the 2 * PARAM_DELTA syndromes */
    compute_syndromes(syndromes, cdw_bytes);

    /* compute the error locator polynomial sigma */
    /* sigma's degree is at most PARAM_DELTA but the FFT requires the extra room */
    deg = compute_elp(sigma, syndromes);

    /* compute the error polynomial error */
    compute_roots(error, sigma);

    /* compute the polynomial z(x) */
    compute_z_poly(z, sigma, deg, syndromes);

    /* compute the error values */
    compute_error_values(error_values, z, error);

    /* correct the errors */
    correct_errors(cdw_bytes, error_values);

    /* retrieve the message from the decoded codeword */
    qsc_memutils_copy(msg, cdw_bytes + (PARAM_G - 1U), PARAM_K);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(cdw_bytes, sizeof cdw_bytes);
}

static uint32_t compare_u32(const uint32_t v1, const uint32_t v2)
{
    return 1U ^ (((v1 - v2) | (v2 - v1)) >> 31);
}

static uint32_t barrett_reduce(uint32_t x) 
{
    uint64_t q;
    uint32_t r;
    uint32_t reduce_flag;
    uint32_t mask;

    q = ((uint64_t)x * PARAM_N_MU) >> 32;
    r = x - (uint32_t)(q * PARAM_N);
    reduce_flag = (((r - PARAM_N) >> 31) ^ 1U);
    mask = (uint32_t)0U - reduce_flag;
    r -= mask & PARAM_N;

    return r;
}

static void vect_generate_random_support1(qsc_keccak_state* ctx, uint32_t* support, uint16_t weight) 
{
    uint8_t rand_bytes[3U] = { 0U };
    uint32_t candidate;
    int32_t is_position_available;

    candidate = 0U;

    for (size_t i = 0U; i < weight;) 
    {
        xof_get_bytes(ctx, rand_bytes, 3);
        candidate = rand_bytes[0U] | (rand_bytes[1U] << 8) | (rand_bytes[2U] << 16);

        if (candidate >= UTILS_REJECTION_THRESHOLD)
        {
            continue;
        }

        candidate = barrett_reduce(candidate);

        is_position_available = 1;

        for (size_t j = 0U; j < i; ++j) 
        {
            if (candidate == support[j]) 
            {
                is_position_available = 0;
                break;
            }
        }

        if (is_position_available == 1)
        {
            support[i] = candidate;
            ++i;
        }
    }
}

static void vect_generate_random_support2(qsc_keccak_state* ctx, uint32_t* support, uint16_t weight)
{
    uint32_t rand_u32[PARAM_OMEGA_R] = { 0U };
    uint32_t found;
    uint32_t mask;

    xof_get_bytes(ctx, (uint8_t*)&rand_u32, 4U * weight);

    for (size_t i = 0U; i < weight; ++i) 
    {
        uint64_t buff = rand_u32[i];
        support[i] = (uint32_t)i + ((buff * (PARAM_N - i)) >> 32);
    }

    for (int32_t i = (weight - 1); i-- > 0;) 
    {
        found = 0U;

        for (size_t j = i + 1U; j < weight; ++j) 
        {
            found |= compare_u32(support[j], support[i]);
        }

        mask = (uint32_t)0U - found;
        support[i] = (mask & i) ^ (~mask & support[i]);
    }
}

static void vect_write_support_to_vector(uint64_t* v, uint32_t* support, uint16_t weight)
{
    uint32_t index_tab[PARAM_OMEGA_R] = { 0U };
    uint64_t bit_tab[PARAM_OMEGA_R] = { 0U };
    uint64_t mask;
    uint64_t val;
    uint32_t tmp;
    int32_t val1;

    for (size_t i = 0U; i < weight; i++)
    {
        index_tab[i] = support[i] >> 6;
        int32_t pos = support[i] & 0x3F;
        bit_tab[i] = ((uint64_t)1) << pos;
    }

    val = 0U;

    for (uint32_t i = 0U; i < VEC_N_SIZE_64; ++i) 
    {
        val = 0U;

        for (uint32_t j = 0U; j < weight; ++j)
        {
            tmp = i - index_tab[j];
            val1 = (int32_t)(1U ^ (((tmp | (uint32_t)(0U - tmp)) >> 31) & 1U));
            mask = -val1;
            val |= (bit_tab[j] & mask);
        }

        v[i] |= val;
    }
}

static void vect_sample_fixed_weight1(qsc_keccak_state* ctx, uint64_t* v, uint16_t weight)
{
    uint32_t support[PARAM_OMEGA_R] = { 0U };

    vect_generate_random_support1(ctx, support, weight);
    vect_write_support_to_vector(v, support, weight);
}

static void vect_sample_fixed_weight2(qsc_keccak_state* ctx, uint64_t* v, uint16_t weight)
{
    uint32_t support[PARAM_OMEGA_R] = { 0U };

    vect_generate_random_support2(ctx, support, weight);
    vect_write_support_to_vector(v, support, weight);
}

static void vect_set_random(qsc_keccak_state* ctx, uint64_t* v)
{
    xof_get_bytes(ctx, (uint8_t*)v, VEC_N_SIZE_BYTES);
    v[VEC_N_SIZE_64 - 1U] &= ((UINT64_C(1) << (PARAM_N % 64U)) - UINT64_C(1));
}

static void vect_add(uint64_t* o, const uint64_t* v1, const uint64_t* v2, uint32_t size)
{
    for (uint32_t i = 0U; i < size; ++i) 
    {
        o[i] = v1[i] ^ v2[i];
    }
}

static uint8_t vect_compare(const uint8_t* v1, const uint8_t* v2, uint32_t size)
{
    uint16_t r = 0x0100U;

    for (size_t i = 0U; i < size; i++)
    {
        r |= v1[i] ^ v2[i];
    }

    return (r - 1U) >> 8;
}

static void vect_truncate(uint64_t* v)
{
    uint64_t mask;
    size_t orig_words;
    size_t new_full_words;
    size_t remaining_bits;

    orig_words = (PARAM_N + 63U) / 64U;
    new_full_words = PARAM_N1N2 / 64U;
    remaining_bits = PARAM_N1N2 % 64U;

    /* mask the last word if there's a partial word */
    if (remaining_bits > 0U)
    {
        mask = (UINT64_C(1) << remaining_bits) - 1U;

        v[new_full_words] &= mask;
        ++new_full_words;
    }

    /* zero out all subsequent words up to the original length */
    for (size_t i = new_full_words; i < orig_words; ++i)
    {
        v[i] = 0U;
    }
}

static void code_encode(uint64_t* em, const uint64_t* m)
{
    uint64_t tmp[VEC_N1_SIZE_64] = { 0U };

    reed_solomon_encode(tmp, m);
    reed_muller_encode(em, tmp);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(tmp, sizeof tmp);
}

static void code_decode(uint64_t* m, const uint64_t* em)
{
    uint64_t tmp[VEC_N1_SIZE_64] = { 0U };

    reed_muller_decode(tmp, em);
    reed_solomon_decode(m, tmp);

    qsc_memutils_secure_erase(tmp, sizeof tmp);
}

static void hqc_dk_pke_from_string(uint64_t* y, const uint8_t* dk_pke)
{
    qsc_keccak_state dk_xof_ctx = { 0U };

    xof_init(&dk_xof_ctx, dk_pke, SEED_BYTES);
    vect_sample_fixed_weight1(&dk_xof_ctx, y, PARAM_OMEGA);

    qsc_memutils_secure_erase(&dk_xof_ctx, sizeof dk_xof_ctx);
}

static void hqc_ek_pke_from_string(uint64_t* h, uint64_t* s, const uint8_t* ek_pke)
{
    qsc_keccak_state ek_xof_ctx = { 0U };

    xof_init(&ek_xof_ctx, ek_pke, SEED_BYTES);
    vect_set_random(&ek_xof_ctx, h);

    qsc_memutils_copy(s, ek_pke + SEED_BYTES, VEC_N_SIZE_BYTES);
}

static void hqc_c_kem_to_string(uint8_t* ct, const qsc_hqc_ciphertext_kem* c_kem)
{
    qsc_memutils_copy(ct, c_kem->c_pke.u, VEC_N_SIZE_BYTES);
    qsc_memutils_copy(ct + VEC_N_SIZE_BYTES, c_kem->c_pke.v, VEC_N1N2_SIZE_BYTES);
    qsc_memutils_copy(ct + VEC_N_SIZE_BYTES + VEC_N1N2_SIZE_BYTES, c_kem->salt, SALT_BYTES);
}

static void hqc_c_kem_from_string(qsc_hqc_ciphertext_pke* c_pke, uint8_t* salt, const uint8_t* ct)
{
    qsc_memutils_copy(c_pke->u, ct, VEC_N_SIZE_BYTES);
    qsc_memutils_copy(c_pke->v, ct + VEC_N_SIZE_BYTES, VEC_N1N2_SIZE_BYTES);
    qsc_memutils_copy(salt, ct + VEC_N_SIZE_BYTES + VEC_N1N2_SIZE_BYTES, SALT_BYTES);
}

static void hqc_pke_keygen(uint8_t* ek_pke, uint8_t* dk_pke, uint8_t* seed)
{
    qsc_keccak_state dk_xof_ctx = { 0U };
    qsc_keccak_state ek_xof_ctx = { 0U };
    uint8_t keypair_seed[2U * SEED_BYTES] = { 0U };
    uint64_t h[VEC_N_SIZE_64] = { 0U };
    uint64_t s[VEC_N_SIZE_64] = { 0U };
    uint64_t x[VEC_N_SIZE_64] = { 0U };
    uint64_t y[VEC_N_SIZE_64] = { 0U };
    uint8_t *seed_dk = keypair_seed;
    uint8_t *seed_ek = keypair_seed + SEED_BYTES;

    /* derive keypair seeds */
    hash_i(keypair_seed, seed);

    /* compute decryption key */
    xof_init(&dk_xof_ctx, seed_dk, SEED_BYTES);
    vect_sample_fixed_weight1(&dk_xof_ctx, y, PARAM_OMEGA);
    vect_sample_fixed_weight1(&dk_xof_ctx, x, PARAM_OMEGA);

    /* compute encryption key */
    xof_init(&ek_xof_ctx, seed_ek, SEED_BYTES);
    vect_set_random(&ek_xof_ctx, h);
    vect_mul(s, y, h);
    vect_add(s, x, s, VEC_N_SIZE_64);

    /* parse encryption key to string */
    qsc_memutils_copy(ek_pke, seed_ek, SEED_BYTES);
    qsc_memutils_copy(ek_pke + SEED_BYTES, s, VEC_N_SIZE_BYTES);

    /* parse decryption key to string */
    qsc_memutils_copy(dk_pke, seed_dk, SEED_BYTES);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(keypair_seed, sizeof keypair_seed);
    qsc_memutils_secure_erase(x, sizeof x);
    qsc_memutils_secure_erase(y, sizeof y);
    qsc_memutils_secure_erase(&dk_xof_ctx, sizeof dk_xof_ctx);
}

static void hqc_pke_encrypt(qsc_hqc_ciphertext_pke* c_pke, const uint8_t* ek_pke, const uint64_t* m, const uint8_t* theta)
{
    qsc_keccak_state theta_xof_ctx = { 0U };
    uint64_t h[VEC_N_SIZE_64] = { 0U };
    uint64_t s[VEC_N_SIZE_64] = { 0U };
    uint64_t r1[VEC_N_SIZE_64] = { 0U };
    uint64_t r2[VEC_N_SIZE_64] = { 0U };
    uint64_t e[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp[VEC_N_SIZE_64] = { 0U };

    /* initialize Xof using theta */
    xof_init(&theta_xof_ctx, theta, SEED_BYTES);

    /* retrieve h and s from public key */
    hqc_ek_pke_from_string(h, s, ek_pke);

    /* generate re, e and r1 */
    vect_sample_fixed_weight2(&theta_xof_ctx, r2, PARAM_OMEGA_R);
    vect_sample_fixed_weight2(&theta_xof_ctx, e, PARAM_OMEGA_E);
    vect_sample_fixed_weight2(&theta_xof_ctx, r1, PARAM_OMEGA_R);

    /* compute u = r1 + r2.h */
    vect_mul(c_pke->u, r2, h);
    vect_add(c_pke->u, r1, c_pke->u, VEC_N_SIZE_64);

    /* compute v = C.encode(m) */
    code_encode(c_pke->v, m);

    /* compute v = C.encode(m) + Truncate(s.r2 + e) */
    vect_mul(tmp, r2, s);
    vect_add(tmp, e, tmp, VEC_N_SIZE_64);
    vect_truncate(tmp);
    vect_add(c_pke->v, c_pke->v, tmp, VEC_N1N2_SIZE_64);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(r1, sizeof r1);
    qsc_memutils_secure_erase(r2, sizeof r2);
    qsc_memutils_secure_erase(e, sizeof e);
    qsc_memutils_secure_erase(tmp, sizeof tmp);
    qsc_memutils_secure_erase(&theta_xof_ctx, sizeof theta_xof_ctx);
}

static uint8_t hqc_pke_decrypt(uint64_t* m, const uint8_t* dk_pke, const qsc_hqc_ciphertext_pke* c_pke)
{
    uint64_t y[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp1[VEC_N_SIZE_64] = { 0U };
    uint64_t tmp2[VEC_N_SIZE_64] = { 0U };

    /* parse decryption key dk_pke */
    hqc_dk_pke_from_string(y, dk_pke);

    /* compute u.y */
    vect_mul(tmp1, y, c_pke->u);
    /* truncate(u.y) */
    vect_truncate(tmp1);
    /* compute v - Truncate(u.y) */
    vect_add(tmp2, c_pke->v, tmp1, VEC_N1N2_SIZE_64);

    /* compute plaintext m */
    code_decode(m, tmp2);

    /* zeroize sensitive data */
    qsc_memutils_secure_erase(y, sizeof y);
    qsc_memutils_secure_erase(tmp1, sizeof tmp1);
    qsc_memutils_secure_erase(tmp2, sizeof tmp2);

    return 0;
}

/**
 * \brief Expand a 32-byte HQC-KEM private seed using SHAKE256.
 * \param[out] seed_pke Derived PKE seed, SEED_BYTES bytes.
 * \param[out] sigma Implicit-rejection secret, PARAM_SECURITY_BYTES bytes.
 * \param[in] seed_kem Private KEM seed, SEED_BYTES bytes.
 * \return No return value; buffers must be valid and nonoverlapping.
 * \note Erases the intermediate sponge state; not internally synchronized.
 */
static void qsc_hqc_ref_derive_keygen_seed_material(uint8_t seed_pke[SEED_BYTES], uint8_t sigma[PARAM_SECURITY_BYTES], const uint8_t seed_kem[SEED_BYTES])
{
    qsc_keccak_state ctx_kem = { 0U };

    xof_init(&ctx_kem, seed_kem, SEED_BYTES);
    xof_get_bytes(&ctx_kem, seed_pke, SEED_BYTES);
    xof_get_bytes(&ctx_kem, sigma, PARAM_SECURITY_BYTES);
    qsc_memutils_secure_erase(&ctx_kem, sizeof(ctx_kem));
}

static void qsc_hqc_ref_encapsulate_from_material(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, const uint8_t m[PARAM_SECURITY_BYTES], const uint8_t salt[SALT_BYTES])
{
    uint8_t ktheta[SHARED_SECRET_BYTES + SEED_BYTES] = { 0U };
    uint8_t theta[SEED_BYTES] = { 0U };
    uint8_t hashpk[SEED_BYTES] = { 0U };
    qsc_hqc_ciphertext_kem c_kem_t = { 0U };

    hash_h(hashpk, publickey);
    hash_g(ktheta, hashpk, m, salt);
    qsc_memutils_copy(theta, ktheta + SHARED_SECRET_BYTES, SEED_BYTES);
    qsc_memutils_copy(c_kem_t.salt, salt, SALT_BYTES);
    hqc_pke_encrypt(&c_kem_t.c_pke, publickey, (const uint64_t*)m, theta);
    hqc_c_kem_to_string(ciphertext, &c_kem_t);
    qsc_memutils_copy(secret, ktheta, SHARED_SECRET_BYTES);
    qsc_memutils_secure_erase(ktheta, sizeof(ktheta)); qsc_memutils_secure_erase(theta, sizeof(theta)); 
    qsc_memutils_secure_erase(hashpk, sizeof(hashpk)); qsc_memutils_secure_erase(&c_kem_t, sizeof(c_kem_t));
}

/**
 * \brief Generate a compressed HQC-2026 keypair from a 32-byte KEM seed.
 * \param[out] publickey Encoded public key, PUBLIC_KEY_BYTES bytes.
 * \param[out] privatekey Compressed private seed, SEED_BYTES bytes.
 * \param[in] rng_generate Callback that fills the private seed and reports success.
 * \return True on success; false for invalid pointers or RNG failure.
 * \note Caller buffers must not overlap. The function is not internally synchronized.
 */
bool qsc_hqc_ref_generate_keypair(uint8_t* publickey, uint8_t* privatekey, bool (*rng_generate)(uint8_t*, size_t))
{
	uint8_t seed_pke[SEED_BYTES] = { 0U };
	uint8_t dk_pke[SEED_BYTES] = { 0U };
	uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };
	bool res = false;

	if (publickey != NULL && privatekey != NULL && rng_generate != NULL)
	{
		res = rng_generate(privatekey, SEED_BYTES);

		if (res == true)
		{
			qsc_hqc_ref_derive_keygen_seed_material(seed_pke, sigma, privatekey);
			hqc_pke_keygen(publickey, dk_pke, seed_pke);
		}
	}

	qsc_memutils_secure_erase(seed_pke, sizeof(seed_pke));
	qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke));
	qsc_memutils_secure_erase(sigma, sizeof(sigma));

	return res;
}

/**
 * \brief Derive a compressed HQC-2026 keypair deterministically.
 * \param[out] publickey Encoded public key, PUBLIC_KEY_BYTES bytes.
 * \param[out] privatekey Seed-based private key, SEED_BYTES bytes.
 * \param[in] seed Input KEM seed, SEED_BYTES bytes, retained by the caller.
 * \return No return value; null pointers produce no output.
 * \note Output buffers must not overlap the input; not internally synchronized.
 */
void qsc_hqc_ref_generate_seeded_keypair(uint8_t* publickey, uint8_t* privatekey, uint8_t* seed)
{
	uint8_t seed_pke[SEED_BYTES] = { 0U };
	uint8_t dk_pke[SEED_BYTES] = { 0U };
	uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };

	if (publickey != NULL && privatekey != NULL && seed != NULL)
	{
		qsc_hqc_ref_derive_keygen_seed_material(seed_pke, sigma, seed);
		hqc_pke_keygen(publickey, dk_pke, seed_pke);
		qsc_memutils_copy(privatekey, seed, SEED_BYTES);
	}

	qsc_memutils_secure_erase(seed_pke, sizeof(seed_pke));
	qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke));
	qsc_memutils_secure_erase(sigma, sizeof(sigma));
}

bool qsc_hqc_ref_encapsulate(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, bool (*rng_generate)(uint8_t*, size_t))
{
    uint8_t m[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t salt[SALT_BYTES] = { 0U };
    bool res;

    res = false;

    if (secret != NULL && ciphertext != NULL && publickey != NULL && rng_generate != NULL) 
    {
        res = (rng_generate(m, PARAM_SECURITY_BYTES) && rng_generate(salt, SALT_BYTES));

        if (res == true) 
        { 
            qsc_hqc_ref_encapsulate_from_material(secret, ciphertext, publickey, m, salt); 
        }
    }

    qsc_memutils_secure_erase(m, sizeof(m)); qsc_memutils_secure_erase(salt, sizeof(salt));

    return res;
}

void qsc_hqc_ref_seeded_encapsulate(uint8_t* secret, uint8_t* ciphertext, const uint8_t* publickey, const uint8_t seed[QSC_HQC_SEED_SIZE])
{
    uint8_t material[PARAM_SECURITY_BYTES + SALT_BYTES] = { 0U };
    qsc_keccak_state ctx = { 0U };

    if (secret != NULL && ciphertext != NULL && publickey != NULL && seed != NULL) 
    {
        xof_init(&ctx, seed, QSC_HQC_SEED_SIZE);
        xof_get_bytes(&ctx, material, (uint32_t)sizeof(material));
        qsc_hqc_ref_encapsulate_from_material(secret, ciphertext, publickey, material, material + PARAM_SECURITY_BYTES);
        qsc_memutils_secure_erase(&ctx, sizeof(ctx));
    }

    qsc_memutils_secure_erase(material, sizeof(material));
}

bool qsc_hqc_ref_decapsulate(uint8_t* secret, const uint8_t* ciphertext, const uint8_t* privatekey)
{
    uint8_t ek_pke[PUBLIC_KEY_BYTES] = { 0U };
    uint8_t dk_pke[SEED_BYTES] = { 0U };
    uint8_t seed_pke[SEED_BYTES] = { 0U };
    uint8_t sigma[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t m_prime[PARAM_SECURITY_BYTES] = { 0U };
    uint8_t hash_ek_kem[SEED_BYTES] = { 0U };
    uint8_t ktheta_prime[SHARED_SECRET_BYTES + SEED_BYTES] = { 0U };
    uint8_t k_bar[SHARED_SECRET_BYTES] = { 0U };
    uint8_t theta_prime[SEED_BYTES] = { 0U };
    qsc_hqc_ciphertext_kem c_kem_t = { 0U };
    qsc_hqc_ciphertext_kem c_kem_prime_t = { 0U };
    uint8_t result;
    bool res;

    result = 1U;
    res = false;

    if (secret != NULL && ciphertext != NULL && privatekey != NULL)
    {
        qsc_hqc_ref_derive_keygen_seed_material(seed_pke, sigma, privatekey);
        hqc_pke_keygen(ek_pke, dk_pke, seed_pke);
        hqc_c_kem_from_string(&c_kem_t.c_pke, c_kem_t.salt, ciphertext);
        result = hqc_pke_decrypt((uint64_t*)m_prime, dk_pke, &c_kem_t.c_pke);
        hash_h(hash_ek_kem, ek_pke);
        hash_g(ktheta_prime, hash_ek_kem, m_prime, c_kem_t.salt);
        qsc_memutils_copy(secret, ktheta_prime, SHARED_SECRET_BYTES);
        qsc_memutils_copy(theta_prime, ktheta_prime + SHARED_SECRET_BYTES, SEED_BYTES);
        hqc_pke_encrypt(&c_kem_prime_t.c_pke, ek_pke, (const uint64_t*)m_prime, theta_prime);
        qsc_memutils_copy(c_kem_prime_t.salt, c_kem_t.salt, SALT_BYTES);
        hash_j(k_bar, hash_ek_kem, sigma, &c_kem_t);
        result |= vect_compare((const uint8_t*)c_kem_t.c_pke.u, (const uint8_t*)c_kem_prime_t.c_pke.u, VEC_N_SIZE_BYTES);
        result |= vect_compare((const uint8_t*)c_kem_t.c_pke.v, (const uint8_t*)c_kem_prime_t.c_pke.v, VEC_N1N2_SIZE_BYTES);
        result |= vect_compare(c_kem_t.salt, c_kem_prime_t.salt, SALT_BYTES);
        result = (uint8_t)(result - 1U);

        for (size_t i = 0U; i < SHARED_SECRET_BYTES; ++i) 
        { 
            secret[i] = (uint8_t)((secret[i] & result) ^ (k_bar[i] & (uint8_t)~result)); 
        }

        res = true;
    }

    qsc_memutils_secure_erase(ek_pke, sizeof(ek_pke)); 
    qsc_memutils_secure_erase(dk_pke, sizeof(dk_pke));
    qsc_memutils_secure_erase(seed_pke, sizeof(seed_pke)); 
    qsc_memutils_secure_erase(sigma, sizeof(sigma)); 
    qsc_memutils_secure_erase(m_prime, sizeof(m_prime)); 
    qsc_memutils_secure_erase(hash_ek_kem, sizeof(hash_ek_kem)); 
    qsc_memutils_secure_erase(ktheta_prime, sizeof(ktheta_prime)); 
    qsc_memutils_secure_erase(k_bar, sizeof(k_bar)); 
    qsc_memutils_secure_erase(theta_prime, sizeof(theta_prime));
    qsc_memutils_secure_erase(&c_kem_t, sizeof(c_kem_t)); 
    qsc_memutils_secure_erase(&c_kem_prime_t, sizeof(c_kem_prime_t));

    return res;
}

