/**
 * \brief Fill deterministic nonsecret key, plaintext, nonce, AAD, or tweak bytes.
 * \param output Writable array of at least length bytes.
 * \param length Number of bytes to initialize.
 * \param index Global KAT index, 0..19, matching the frozen generator.
 * \param salt Per-field byte-domain constant.
 */
static void qsctest_rcs_kat_fill(uint8_t* output, size_t length, size_t index, uint8_t salt)
{
    size_t i;

    for (i = 0U; i < length; ++i)
    {
        output[i] = (uint8_t)((i * 29U + index * 17U + (size_t)salt) & 255U);
    }
}

