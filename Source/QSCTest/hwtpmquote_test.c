/** \struct hwtpmquote_fixture
 * \brief Owned signed quote data and expected test policy; no device dependencies.
 */
typedef struct hwtpmquote_fixture
{
	uint8_t quote[256U]; /**< Serialized TPMS_ATTEST test quote. */
	size_t quotelen; /**< Actual quote length in bytes. */
	uint8_t signature[72U]; /**< Serialized SHA256 ECDSA TPMT_SIGNATURE. */
	uint8_t nonce[20U]; /**< Challenge bytes. */
	uint8_t akname[34U]; /**< Trusted SHA-256 AK Name bytes. */
	uint8_t pcrdigest[32U]; /**< Reference PCR digest bytes. */
	uint8_t akpublic[64U]; /**< Raw Qx||Qy P-256 public key. */
	qsc_hw_tpm_quote_policy policy; /**< Pointer-backed policy referencing this fixture. */
} hwtpmquote_fixture;

/** \brief Encode a two-byte big-endian integer in a test fixture.
 * \param output Writable output of at least two bytes.
 * \param value Integer to encode.
 */
static void hwtpmquote_test_u16(uint8_t* output, uint16_t value)
{
	output[0U] = (uint8_t)(value >> 8U);
	output[1U] = (uint8_t)value;
}

/** \brief Produce a signed standards-shaped TPM2 Quote using QSC's P-256 signer.
 * \param fixture Receives owned serialized quote/signature and expected policy.
 * \return true when all signed fixture components are generated.
 * \note The signature is mathematically valid but is not generated by an actual TPM.
 */
static bool hwtpmquote_test_fixture(hwtpmquote_fixture* fixture)
{
	uint8_t privatekey[96U] = { 0U };
	uint8_t seed[32U] = { 0U };
	uint8_t signedmsg[320U] = { 0U };
	size_t slen;
	size_t i;
	size_t offset;
	bool valid;

	valid = false;
	slen = 0U;
	offset = 0U;

	if (fixture != NULL)
	{
		qsc_memutils_clear(fixture, sizeof(*fixture));

		for (i = 0U; i < sizeof(seed); ++i)
		{
			seed[i] = (uint8_t)(i + 1U);
		}

		if (qsc_ecdsap256_keypair(fixture->akpublic, privatekey, seed) == 0)
		{
			for (i = 0U; i < sizeof(fixture->nonce); ++i)
			{
				fixture->nonce[i] = (uint8_t)(0x40U + i);
			}

			fixture->akname[0U] = 0U;
			fixture->akname[1U] = 0x0BU;
			for (i = 2U; i < sizeof(fixture->akname); ++i)
			{
				fixture->akname[i] = (uint8_t)(0x70U + i);
			}

			for (i = 0U; i < sizeof(fixture->pcrdigest); ++i)
			{
				fixture->pcrdigest[i] = (uint8_t)(0x90U + i);
			}

			/* TPMS_ATTEST: magic, type, AK Name, extraData challenge. */
			fixture->quote[offset++] = 0xFFU;
			fixture->quote[offset++] = 0x54U;
			fixture->quote[offset++] = 0x43U;
			fixture->quote[offset++] = 0x47U;
			fixture->quote[offset++] = 0x80U;
			fixture->quote[offset++] = 0x18U;
			hwtpmquote_test_u16(fixture->quote + offset, sizeof(fixture->akname));
			offset += 2U;
			qsc_memutils_copy(fixture->quote + offset, fixture->akname, sizeof(fixture->akname));
			offset += sizeof(fixture->akname);
			hwtpmquote_test_u16(fixture->quote + offset, sizeof(fixture->nonce));
			offset += 2U;
			qsc_memutils_copy(fixture->quote + offset, fixture->nonce, sizeof(fixture->nonce));
			offset += sizeof(fixture->nonce);

			/* TPMS_CLOCK_INFO: clock, reset, restart, safe; followed by firmwareVersion. */
			offset += 16U;
			fixture->quote[offset++] = 1U;
			offset += 8U;

			/* Quote PCR selection: SHA256 bank PCR 0 and 32-byte digest. */
			qsc_intutils_be32to8(fixture->quote + offset, 1U);
			offset += 4U;
			fixture->quote[offset++] = 0U;
			fixture->quote[offset++] = 0x0BU;
			fixture->quote[offset++] = 3U;
			fixture->quote[offset++] = 1U;
			fixture->quote[offset++] = 0U;
			fixture->quote[offset++] = 0U;
			hwtpmquote_test_u16(fixture->quote + offset, 32U);
			offset += 2U;
			qsc_memutils_copy(fixture->quote + offset, fixture->pcrdigest, 32U);
			offset += 32U;
			fixture->quotelen = offset;

			if (qsc_ecdsap256_sign(signedmsg, &slen, fixture->quote, fixture->quotelen, privatekey) == 0 &&
				slen == 64U + fixture->quotelen)
			{
				fixture->signature[0U] = 0U;
				fixture->signature[1U] = 0x18U;
				fixture->signature[2U] = 0U;
				fixture->signature[3U] = 0x0BU;
				fixture->signature[4U] = 0U;
				fixture->signature[5U] = 32U;
				qsc_memutils_copy(fixture->signature + 6U, signedmsg, 32U);
				fixture->signature[38U] = 0U;
				fixture->signature[39U] = 32U;
				qsc_memutils_copy(fixture->signature + 40U, signedmsg + 32U, 32U);

				fixture->policy.nonce = fixture->nonce;
				fixture->policy.noncelen = sizeof(fixture->nonce);
				fixture->policy.akname = fixture->akname;
				fixture->policy.aknamelen = sizeof(fixture->akname);
				fixture->policy.akpublic = fixture->akpublic;
				fixture->policy.pcrdigest = fixture->pcrdigest;
				fixture->policy.pcrselect[0U] = 1U;
				fixture->policy.pcrselect[1U] = 0U;
				fixture->policy.pcrselect[2U] = 0U;
				fixture->policy.require_safe_clock = true;
				valid = true;
			}
		}
	}

	qsc_memutils_secure_erase(privatekey, sizeof(privatekey));
	qsc_memutils_secure_erase(seed, sizeof(seed));
	qsc_memutils_secure_erase(signedmsg, sizeof(signedmsg));

	return valid;
}

/** \brief Accept a correctly signed quote with expected AK, nonce and PCR policy.
 * \return true for successful end-to-end quote verification.
 */
static bool hwtpmquote_test_valid(void)
{
	hwtpmquote_fixture fixture;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) == qsc_hw_status_success);
	qsctest_print_line(valid ? "[PASS] Stage8 verified signed TPM quote" : "[FAIL] Stage8 verified signed TPM quote");
	return valid;
}

/** \brief Reject quote replay against a different verifier nonce.
 * \return true only for rejected stale challenge.
 */
static bool hwtpmquote_test_nonce(void)
{
	hwtpmquote_fixture fixture;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	fixture.nonce[0U] ^= 1U;
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) != qsc_hw_status_success);
	qsctest_print_line(valid ? "[PASS] Stage8 nonce replay rejected" : "[FAIL] Stage8 nonce replay rejected");
	return valid;
}

