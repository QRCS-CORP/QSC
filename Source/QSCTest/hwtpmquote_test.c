/** \brief Reject truncated and appended TPM wire encodings.
 * \return true only if both noncanonical lengths fail verification.
 */
static bool hwtpmquote_test_quote_lengths(void)
{
	hwtpmquote_fixture fixture;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen - 1U,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) != qsc_hw_status_success);
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen + 1U,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) != qsc_hw_status_success);
	qsctest_print_line(valid ? "[PASS] Stage8 quote truncation and trailing data rejected" : "[FAIL] Stage8 quote truncation and trailing data rejected");
	return valid;
}

