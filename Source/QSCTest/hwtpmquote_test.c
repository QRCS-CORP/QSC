/** \brief Reject non-safe TPM clock claims under the required clock policy.
 * \return true only when clockInfo.safe=0 is rejected.
 */
static bool hwtpmquote_test_clock(void)
{
	hwtpmquote_fixture fixture;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	fixture.quote[6U + 2U + 34U + 2U + 20U + 16U] = 0U;
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) != qsc_hw_status_success);
	qsctest_print_line(valid ? "[PASS] Stage8 unsafe TPM clock rejected" : "[FAIL] Stage8 unsafe TPM clock rejected");
	return valid;
}

/** \brief Reject NULL or absent trusted attestation parameters.
 * \return true only when all null input paths fail closed.
 */
static bool hwtpmquote_test_invalid(void)
{
	hwtpmquote_fixture fixture;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	valid = valid && (qsc_hw_tpm_quote_verify(NULL, fixture.quotelen,
		fixture.signature, sizeof(fixture.signature), &fixture.policy) == qsc_hw_status_invalid_parameter);
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen,
		fixture.signature, sizeof(fixture.signature), NULL) == qsc_hw_status_invalid_parameter);
	valid = valid && (qsc_hw_tpm_quote_verify(fixture.quote, fixture.quotelen,
		NULL, sizeof(fixture.signature), &fixture.policy) == qsc_hw_status_invalid_parameter);
	qsctest_print_line(valid ? "[PASS] Stage8 null and missing policy inputs rejected" : "[FAIL] Stage8 null and missing policy inputs rejected");
	return valid;
}

/** \brief Accept a canonical quote envelope and reject additional bytes.
 * \return true only if both authenticated envelope and strict framing checks pass.
 */
static bool hwtpmquote_test_envelope(void)
{
	hwtpmquote_fixture fixture;
	uint8_t envelope[4U + 256U + 72U] = { 0U };
	size_t offset;
	bool valid;

	valid = hwtpmquote_test_fixture(&fixture);
	offset = 0U;
	hwtpmquote_test_u16(envelope + offset, (uint16_t)fixture.quotelen);
	offset += 2U;
	qsc_memutils_copy(envelope + offset, fixture.quote, fixture.quotelen);
	offset += fixture.quotelen;
	hwtpmquote_test_u16(envelope + offset, (uint16_t)sizeof(fixture.signature));
	offset += 2U;
	qsc_memutils_copy(envelope + offset, fixture.signature, sizeof(fixture.signature));
	offset += sizeof(fixture.signature);
	valid = valid && (qsc_hw_tpm_quote_envelope_verify(envelope, offset,
		&fixture.policy) == qsc_hw_status_success);
	valid = valid && (qsc_hw_tpm_quote_envelope_verify(envelope, offset + 1U,
		&fixture.policy) != qsc_hw_status_success);
	valid = valid && (qsc_hw_tpm_quote_envelope_verify(envelope, 3U,
		&fixture.policy) == qsc_hw_status_invalid_parameter);
	qsctest_print_line(valid ? "[PASS] Stage8 authenticated quote envelope framing" : "[FAIL] Stage8 authenticated quote envelope framing");
	return valid;
}

bool qsctest_hwtpmquote_run(void)
{
	bool valid;

	valid = true;
	valid = hwtpmquote_test_valid() && valid;
	valid = hwtpmquote_test_nonce() && valid;
	valid = hwtpmquote_test_pcr_digest() && valid;
	valid = hwtpmquote_test_pcr_selection() && valid;
	valid = hwtpmquote_test_ak_name() && valid;
	valid = hwtpmquote_test_tampered_signature() && valid;
	valid = hwtpmquote_test_bad_scheme() && valid;
	valid = hwtpmquote_test_quote_lengths() && valid;
	valid = hwtpmquote_test_sig_lengths() && valid;
	valid = hwtpmquote_test_quote_header() && valid;
	valid = hwtpmquote_test_clock() && valid;
	valid = hwtpmquote_test_invalid() && valid;
	valid = hwtpmquote_test_envelope() && valid;

	return valid;
}

