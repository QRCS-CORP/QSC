/**
 * \brief Verify an OpenSSL ECDSA certificate and reject a corrupted signature.
 * \param certificate Signed X.509 DER bytes.
 * \param certlen DER byte count.
 * \return True only if valid signature is accepted and modified signature rejected.
 * \note Allocates and releases independent certificate scratch and verification state.
 */
static bool stage5_verify_certificate(const uint8_t* certificate, size_t certlen)
{
	qsc_x509_certificate* cert;
	uint8_t* scratch;
	uint8_t* corrupted;
	qsc_x509_verify_state vstate;
	qsc_asn1_status status;
	bool res;

	cert = (qsc_x509_certificate*)qsc_memutils_malloc(sizeof(qsc_x509_certificate));
	scratch = (uint8_t*)qsc_memutils_malloc(65536U);
	corrupted = (uint8_t*)qsc_memutils_malloc(certlen);
	res = false;

	if ((certificate != NULL) && (certlen != 0U) && (cert != NULL) && (scratch != NULL) && (corrupted != NULL))
	{
		qsc_memutils_clear(cert, sizeof(qsc_x509_certificate));
		qsc_memutils_clear(scratch, 65536U);
		qsc_memutils_copy(corrupted, certificate, certlen);
		qsc_x509_qsc_verify_state_initialize(&vstate, scratch, 65536U);
		status = qsc_x509_certificate_decode_der(certificate, certlen, cert);

		if (status == QSC_ASN1_STATUS_SUCCESS)
		{
			res = qsc_x509_qsc_signature_verify(cert, cert, &vstate);
		}

		if (res == true)
		{
			corrupted[certlen - 1U] ^= 0x01U;
			qsc_x509_certificate_clear(cert);
			status = qsc_x509_certificate_decode_der(corrupted, certlen, cert);
			res = (status == QSC_ASN1_STATUS_SUCCESS) &&
				(qsc_x509_qsc_signature_verify(cert, cert, &vstate) == false);
		}
	}

	if (cert != NULL)
	{
		qsc_x509_certificate_clear(cert);
		qsc_memutils_alloc_free(cert);
	}

	if (scratch != NULL)
	{
		qsc_memutils_secure_erase(scratch, 65536U);
		qsc_memutils_alloc_free(scratch);
	}

	if (corrupted != NULL)
	{
		qsc_memutils_secure_erase(corrupted, certlen);
		qsc_memutils_alloc_free(corrupted);
	}

	return res;
}

